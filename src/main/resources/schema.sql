-- The LogCloud transaction log (Atomikos ExtremeTransactions 6.0), shared by all nodes.
-- IF NOT EXISTS: every node runs this script at startup.

CREATE TABLE IF NOT EXISTS COORDINATOR (
	OWNING_RECOVERY_DOMAIN_NAME VARCHAR(45) NOT NULL,
	ID VARCHAR(36) NOT NULL,
	STATE VARCHAR(36) NOT NULL,
	EXPIRES BIGINT NOT NULL,
	SUPERIOR_ID VARCHAR(64),
	RECOVERY_DOMAIN_NAME VARCHAR(45) NOT NULL);

CREATE TABLE IF NOT EXISTS LOG_CLOUD_STARTUP_CONFIG (
	OWNING_RECOVERY_DOMAIN_NAME VARCHAR(45) NOT NULL,
	PROPERTY_NAME VARCHAR(2000) NOT NULL,
	PROPERTY_VALUE VARCHAR(2000) NOT NULL,
	CONSTRAINT LOG_CLOUD_STARTUP_CONFIG_PK PRIMARY KEY (OWNING_RECOVERY_DOMAIN_NAME, PROPERTY_NAME));

CREATE TABLE IF NOT EXISTS LEADER (
	OWNING_RECOVERY_DOMAIN_NAME VARCHAR(45) NOT NULL,
	ACTIVE_JVM_ID VARCHAR(2000) NOT NULL DEFAULT 'NONE',
	EXPIRY BIGINT NOT NULL DEFAULT 0,
	CONSTRAINT ACTIVE_JVM_ID_PK PRIMARY KEY (OWNING_RECOVERY_DOMAIN_NAME, ACTIVE_JVM_ID));

CREATE TABLE IF NOT EXISTS REMOTE_PARTICIPANT (
	OWNING_RECOVERY_DOMAIN_NAME VARCHAR(45) NOT NULL,
	COORDINATOR_ID VARCHAR(36) NOT NULL,
	REMOTE_PARTICIPANT_URI VARCHAR(64) NOT NULL);

CREATE TABLE IF NOT EXISTS RECOVERY_DECISION (
	OWNING_RECOVERY_DOMAIN_NAME VARCHAR(45) NOT NULL,
	COORDINATOR_ID VARCHAR(36) NOT NULL,
	DECISION VARCHAR(6) NOT NULL,
	DECISION_TIME BIGINT NOT NULL,
	FORGOTTEN_TIME BIGINT,
	CONSTRAINT RECOVERY_DECISION_PK PRIMARY KEY (COORDINATOR_ID));

CREATE TABLE IF NOT EXISTS RECOVERY_ACTION_LOG (
	OWNING_RECOVERY_DOMAIN_NAME VARCHAR(45) NOT NULL,
	COORDINATOR_ID VARCHAR(36) NOT NULL,
	XID VARCHAR(2000) NOT NULL,
	ACTIVE_JVM_ID VARCHAR(2000) NOT NULL,
	ACTION VARCHAR(20) NOT NULL,
	DECISION_TIME BIGINT NOT NULL,
	ID VARCHAR(36) NOT NULL);

CREATE TABLE IF NOT EXISTS RECOVERY_HEURISTIC_LOG (
	OWNING_RECOVERY_DOMAIN_NAME VARCHAR(45) NOT NULL,
	COORDINATOR_ID VARCHAR(36) NOT NULL,
	XID VARCHAR(2000) NOT NULL,
	ACTIVE_JVM_ID VARCHAR(2000) NOT NULL,
	OUTCOME VARCHAR(20) NOT NULL,
	DECISION_TIME BIGINT NOT NULL);
